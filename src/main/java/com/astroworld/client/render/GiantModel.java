package com.astroworld.client.render;

import com.astroworld.ShowPhase;
import com.astroworld.client.ShowState;
import com.astroworld.config.AstroConfig;
import com.mojang.blaze3d.systems.RenderSystem;
import net.minecraft.client.MinecraftClient;
import net.minecraft.client.render.*;
import net.minecraft.client.util.math.MatrixStack;
import net.minecraft.util.Identifier;
import net.minecraft.util.math.MathHelper;
import net.minecraft.util.math.RotationAxis;
import net.minecraft.util.math.Vec3d;
import org.joml.Matrix4f;

/**
 * The giant performer: a detailed cuboid model (head, hair, braids, visor, jacket, arms, legs, boots,
 * pendant, glowing shoulder plates) drawn in two passes: lit base + additive emissive glow.
 * Textures are 128x128 and are generated by tools/generate_assets.py - replace them with your own art if you like.
 * (Stylised fan tribute; not a photographic likeness.)
 */
public final class GiantModel {
    public static final Identifier TEX = new Identifier("astroworld", "textures/entity/giant.png");
    public static final Identifier TEX_GLOW = new Identifier("astroworld", "textures/entity/giant_glow.png");
    private static final int TW = 128, TH = 128;
    private static final float MODEL_H = 33f;   // units incl. hair

    private GiantModel() {}

    /** All animated angles, computed once per frame. */
    private static final class Pose {
        float bodyY, bodyLeanX, bodyTwistY, headPitch, headYaw, headRoll;
        float armLZ, armRZ, armLX, armRX, legLX, legRX, legSpread, braid, forearm;
    }

    private static Pose pose(float pt) {
        Pose p = new Pose();
        float t = ShowState.showTime(pt);
        ShowPhase ph = ShowState.phase();
        float pr = ph.progress(t);
        float beat = ShowState.beat(pt);
        float bp = beat * ((float) (Math.PI * 2));
        float e = ShowState.energy(pt);
        float pulse = ShowState.pulse(pt);
        switch (ph) {
            case PRE_SHOW -> {   // standing still, head down, barely breathing
                p.headPitch = 18 + MathHelper.sin(t * 0.05f) * 2;
                p.armLZ = 12; p.armRZ = -12;
            }
            case ARRIVAL -> {    // head rises, arms open wide in a slow, heavy gesture
                float k = MathHelper.clamp((pr - 0.45f) / 0.55f, 0, 1);
                k = k * k * (3 - 2 * k);
                p.headPitch = MathHelper.lerp(k, 18, -12);
                p.armLZ = MathHelper.lerp(k, 12, 150); p.armRZ = -p.armLZ;
                p.bodyLeanX = -6 * k;
                p.bodyY = pulse * 0.6f * k;
            }
            case THE_SHOW -> {   // bounce, alternating arm swings, head nods on the beat
                p.bodyY = Math.abs(MathHelper.sin(bp * 0.5f)) * 1.4f;
                p.headPitch = MathHelper.sin(bp) * 8 + 4;
                p.headYaw = MathHelper.sin(bp * 0.25f) * 18;
                float s = MathHelper.sin(bp * 0.5f);
                p.armLZ = 65 + 45 * s; p.armRZ = -(65 - 45 * s);
                p.armLX = MathHelper.sin(bp) * 20; p.armRX = -MathHelper.sin(bp) * 20;
                p.legLX = MathHelper.sin(bp * 0.5f) * 14; p.legRX = -p.legLX;
                p.bodyTwistY = MathHelper.sin(bp * 0.5f) * 8;
                p.forearm = 20 * pulse;
            }
            case ASTROWORLD_CHAOS -> { // jumping, hands to the sky, violent head banging
                p.bodyY = Math.abs(MathHelper.sin(bp)) * 4.5f;
                p.headPitch = MathHelper.sin(bp * 2) * 28;
                p.headRoll = MathHelper.sin(bp) * 10;
                p.armLZ = 155 + 25 * MathHelper.sin(bp * 2);
                p.armRZ = -(155 + 25 * MathHelper.sin(bp * 2 + 1.2f));
                p.armLX = MathHelper.sin(bp) * 15; p.armRX = MathHelper.sin(bp + 1) * 15;
                p.legSpread = 12 + 8 * pulse;
                p.legLX = MathHelper.sin(bp) * 10; p.legRX = -p.legLX;
                p.bodyLeanX = MathHelper.sin(bp * 2) * 6;
            }
            case FINALE -> {     // arms spread, slow bow at the very end
                float bow = MathHelper.clamp((pr - 0.75f) / 0.25f, 0, 1);
                p.armLZ = 95 + 6 * MathHelper.sin(bp * 0.5f); p.armRZ = -p.armLZ;
                p.headPitch = -6 + bow * 40;
                p.bodyLeanX = bow * 25;
                p.bodyY = (1 - bow) * Math.abs(MathHelper.sin(bp * 0.5f)) * 1.5f;
            }
            default -> { }
        }
        p.braid = MathHelper.sin(bp + 0.5f) * 14 * e + MathHelper.sin(t * 0.07f) * 3;
        return p;
    }

    /** Renders both passes at the stage. {@code ms} must already be translated to camera-relative space. */
    public static void render(MatrixStack ms, float pt) {
        float reveal = ShowState.reveal(pt);
        if (reveal <= 0.003f) return;
        AstroConfig cfg = AstroConfig.INSTANCE;
        float scale = cfg.giantHeightBlocks / MODEL_H;
        Pose p = pose(pt);
        float t = ShowState.showTime(pt);
        ShowPhase ph = ShowState.phase();
        // silhouette (black, translucent) until the arrival flash, then full colour
        float unveil = ShowState.unveil(pt);

        ms.push();
        Vec3d st = ShowState.stage;
        ms.translate(st.x, st.y + 6 * scale * 0.0 + stageLift(pt), st.z);
        ms.multiply(RotationAxis.POSITIVE_Y.rotationDegrees(ShowState.yaw));
        ms.scale(scale, scale, scale);
        ms.translate(0, p.bodyY, 0);

        for (int pass = 0; pass < 2; pass++) {
            boolean glow = pass == 1;
            if (glow && unveil <= 0.01f) continue;
            RenderSystem.setShader(GameRenderer::getPositionColorTexProgram);
            RenderSystem.setShaderTexture(0, glow ? TEX_GLOW : TEX);
            RenderSystem.enableBlend();
            if (glow) RenderSystem.blendFunc(com.mojang.blaze3d.platform.GlStateManager.SrcFactor.SRC_ALPHA, com.mojang.blaze3d.platform.GlStateManager.DstFactor.ONE);
            else RenderSystem.defaultBlendFunc();
            RenderSystem.disableCull();
            RenderSystem.enableDepthTest();
            BufferBuilder bb = Tessellator.getInstance().getBuffer();
            bb.begin(VertexFormat.DrawMode.QUADS, VertexFormats.POSITION_COLOR_TEXTURE);

            // colour: base is shaded & dark-tinted during silhouette; glow cycles hue with the beat
            float amb = MathHelper.lerp(unveil, 0.0f, 0.55f + 0.45f * ShowState.pulse(pt));
            float a = glow ? unveil : MathHelper.lerp(unveil, reveal, 1f);
            int tint = glow ? Gfx.hsv(t * 0.004f + 0.02f * ShowState.beat(pt), 0.75f, 1f) : Gfx.rgb(amb, amb, amb);
            drawParts(bb, ms, p, tint, a, glow);
            Tessellator.getInstance().draw();
        }
        RenderSystem.defaultBlendFunc();
        RenderSystem.enableCull();
        ms.pop();
    }

    /** The giant stands on the raised stage deck. */
    public static float stageLift(float pt) { return 5f * StageRenderer.deckRise(pt); }

    // ---------------------------------------------------------------- parts

    private static void drawParts(BufferBuilder bb, MatrixStack ms, Pose p, int tint, float a, boolean glow) {
        float r = (tint >> 16 & 255) / 255f, g = (tint >> 8 & 255) / 255f, b = (tint & 255) / 255f;

        // legs + boots (pivot at hip y=12)
        for (int side = -1; side <= 1; side += 2) {
            ms.push();
            ms.translate(side * 2, 12, 0);
            ms.multiply(RotationAxis.POSITIVE_X.rotationDegrees(side < 0 ? p.legRX : p.legLX));
            ms.multiply(RotationAxis.POSITIVE_Z.rotationDegrees(-side * p.legSpread));
            cuboid(bb, ms, -2, -12, -2, 4, 12, 4, 0, 64, r, g, b, a);
            cuboid(bb, ms, -2.5f, -12, -3, 5, 3, 6, 24, 64, r, g, b, a);
            ms.pop();
        }

        // torso group (lean/twist around the waist)
        ms.push();
        ms.translate(0, 12, 0);
        ms.multiply(RotationAxis.POSITIVE_X.rotationDegrees(p.bodyLeanX));
        ms.multiply(RotationAxis.POSITIVE_Y.rotationDegrees(p.bodyTwistY));
        ms.translate(0, -12, 0);
        cuboid(bb, ms, -4, 12, -2, 8, 12, 4, 0, 32, r, g, b, a);
        cuboid(bb, ms, -4.5f, 12, -2.5f, 9, 4, 5, 0, 32, r, g, b, a);       // puffer-jacket hem (reuses body texture)
        cuboid(bb, ms, -1.5f, 17.5f, 2.1f, 3, 3, 1, 64, 16, r, g, b, a);     // pendant

        // arms (pivot at shoulder y=22)
        for (int side = -1; side <= 1; side += 2) {
            ms.push();
            ms.translate(side * 6, 22, 0);
            ms.multiply(RotationAxis.POSITIVE_Z.rotationDegrees(side > 0 ? p.armLZ : p.armRZ));
            ms.multiply(RotationAxis.POSITIVE_X.rotationDegrees(side > 0 ? p.armLX : p.armRX));
            cuboid(bb, ms, -2, -12, -2, 4, 12, 4, 32, 32, r, g, b, a);
            cuboid(bb, ms, -3.0f, 0.2f, -3.0f, 6, 2, 6, 80, 0, r, g, b, a);   // shoulder pad (glow)
            ms.pop();
        }

        // head group
        ms.push();
        ms.translate(0, 24, 0);
        ms.multiply(RotationAxis.POSITIVE_X.rotationDegrees(p.headPitch));
        ms.multiply(RotationAxis.POSITIVE_Y.rotationDegrees(p.headYaw));
        ms.multiply(RotationAxis.POSITIVE_Z.rotationDegrees(p.headRoll));
        cuboid(bb, ms, -4, 0, -4, 8, 8, 8, 0, 0, r, g, b, a);
        cuboid(bb, ms, -4.5f, 6.5f, -4.5f, 9, 3, 9, 0, 16, r, g, b, a);      // hair cap
        cuboid(bb, ms, -4.5f, 0.5f, -4.5f, 9, 6, 2, 36, 16, r, g, b, a);     // hair back
        cuboid(bb, ms, -4, 3.2f, 4.05f, 8, 2, 1, 0, 28, r, g, b, a);          // glowing visor
        // braids swinging from the back of the head
        for (int i = -1; i <= 1; i++) {
            ms.push();
            ms.translate(i * 2.6f, 6, -4.3f);
            ms.multiply(RotationAxis.POSITIVE_X.rotationDegrees(p.braid + i * 6));
            ms.multiply(RotationAxis.POSITIVE_Z.rotationDegrees(p.braid * 0.4f * i));
            cuboid(bb, ms, -1, -10, -1, 2, 10, 2, 64, 0, r, g, b, a);
            ms.pop();
        }
        ms.pop();
        ms.pop();
    }

    // ---------------------------------------------------------------- cuboid with Minecraft-style UV unwrap

    private static void cuboid(BufferBuilder bb, MatrixStack ms, float x, float y, float z, float w, float h, float d,
                               int u, int v, float cr, float cg, float cb, float ca) {
        Matrix4f m = ms.peek().getPositionMatrix();
        float x1 = x + w, y1 = y + h, z1 = z + d;
        int iw = Math.round(w), ih = Math.round(h), id = Math.round(d);
        // front (+z): u grows with +x
        face(bb, m, x, y, z1, x1, y, z1, x1, y1, z1, x, y1, z1, u + id, v + id, iw, ih, cr * .85f, cg * .85f, cb * .85f, ca);
        // back (-z): u grows with -x
        face(bb, m, x1, y, z, x, y, z, x, y1, z, x1, y1, z, u + 2 * id + iw, v + id, iw, ih, cr * .85f, cg * .85f, cb * .85f, ca);
        // right (-x side of the character, at x): u grows with +z
        face(bb, m, x, y, z, x, y, z1, x, y1, z1, x, y1, z, u, v + id, id, ih, cr * .7f, cg * .7f, cb * .7f, ca);
        // left (+x side, at x1): u grows with -z
        face(bb, m, x1, y, z1, x1, y, z, x1, y1, z, x1, y1, z1, u + id + iw, v + id, id, ih, cr * .7f, cg * .7f, cb * .7f, ca);
        // top
        face(bb, m, x, y1, z, x1, y1, z, x1, y1, z1, x, y1, z1, u + id, v, iw, id, cr, cg, cb, ca);
        // bottom
        face(bb, m, x, y, z1, x1, y, z1, x1, y, z, x, y, z, u + id + iw, v, iw, id, cr * .5f, cg * .5f, cb * .5f, ca);
    }

    /** Quad corners BL, BR, TR, TL ; (tu,tv) = top-left pixel of the region, tw/th its size. */
    private static void face(BufferBuilder bb, Matrix4f m,
                             float ax, float ay, float az, float bx, float by, float bz,
                             float cx, float cy, float cz, float dx, float dy, float dz,
                             int tu, int tv, int tw, int th, float r, float g, float b, float a) {
        float u0 = tu / (float) TW, u1 = (tu + tw) / (float) TW, v0 = tv / (float) TH, v1 = (tv + th) / (float) TH;
        bb.vertex(m, ax, ay, az).color(r, g, b, a).texture(u0, v1).next();
        bb.vertex(m, bx, by, bz).color(r, g, b, a).texture(u1, v1).next();
        bb.vertex(m, cx, cy, cz).color(r, g, b, a).texture(u1, v0).next();
        bb.vertex(m, dx, dy, dz).color(r, g, b, a).texture(u0, v0).next();
    }
}
